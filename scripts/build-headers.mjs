// Writes public/_headers (Cloudflare Pages / Netlify format) from src/lib/security/headers.json,
// so the HTTP headers and the CSP <meta> tag always come from the same source.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const config = JSON.parse(readFileSync(join(root, "src/lib/security/headers.json"), "utf8"));

const csp = Object.entries({ ...config.csp, ...config.cspHeaderOnly })
  .map(([name, values]) => `${name} ${values.join(" ")}`)
  .join("; ");

const lines = ["# Generated by scripts/build-headers.mjs from src/lib/security/headers.json. Do not edit.", "/*"];
lines.push(`  Content-Security-Policy: ${csp}`);
for (const [name, value] of Object.entries(config.headers)) lines.push(`  ${name}: ${value}`);
for (const [path, value] of Object.entries(config.cache)) {
  lines.push("", path, `  Cache-Control: ${value}`);
}

writeFileSync(join(root, "public", "_headers"), lines.join("\n") + "\n");
console.log("Wrote public/_headers");
