// Writes public/third-party-notices.txt: the licenses of everything the site ships —
// every production npm dependency, plus code bundled inside WebAssembly files and fonts
// that npm metadata doesn't describe.
import { execSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const nm = (...p) => join(root, "node_modules", ...p);

// Production dependency tree (no dev tools). A fixed command string: no outside input reaches the shell.
const tree = JSON.parse(execSync("npm ls --omit=dev --all --json", { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }));
const packages = new Map();
(function walk(deps) {
  for (const [name, info] of Object.entries(deps ?? {})) {
    if (!info.version || packages.has(`${name}@${info.version}`)) continue;
    packages.set(`${name}@${info.version}`, name);
    walk(info.dependencies);
  }
})(tree.dependencies);

function licenseText(dir) {
  if (!existsSync(dir)) return null;
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying|notice)(\.|-|$)/i.test(f));
  return file ? readFileSync(join(dir, file), "utf8").trim() : null;
}

const sections = [];
for (const [id, name] of [...packages].sort((a, b) => a[0].localeCompare(b[0]))) {
  const dir = nm(...name.split("/"));
  // Optional platform packages (e.g. sharp binaries for other OSes) may not be installed; they aren't shipped.
  if (!existsSync(join(dir, "package.json"))) continue;
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "see text";
  const text = licenseText(dir) ?? `Licensed under ${license}. No license file is included in the package.`;
  sections.push(`${id} — ${license}\n${pkg.homepage ?? ""}\n\n${text}`);
}

